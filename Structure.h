//Structure.h
#pragma once
#include <iostream>
#include <fstream>
#include <string>

using namespace std;

// Вход: строка.
// Что делает: переводит символы строки в верхний регистр с учетом кодировки CP1251.
// Выход: преобразованная строка в верхнем регистре.
string toUpperString(string s);

// Узел списка форм контроля (ветви структуры)
struct EventNode {
    string eventName;
    EventNode* next;
};

// Узел списка учебных предметов (ствол структуры)
struct SubjectNode {
    string subjectName;
    EventNode* eventHead;
    SubjectNode* next;
};

// Класс динамической двухуровневой структуры
class StudyStructure {
private:
    SubjectNode* subjectHead;

public:
    // Вход: нет.
    // Что делает: инициализирует пустую динамическую структуру.
    // Выход: объект создан.
    StudyStructure();

    // Вход: нет.
    // Что делает: освобождает всю динамическую память структуры.
    // Выход: память очищена.
    ~StudyStructure();

    // Вход: название учебного предмета.
    // Что делает: добавляет предмет в конец списка предметов.
    // Выход: структура обновлена.
    void addSubject(string subject);

    // Вход: название предмета, название формы контроля.
    // Что делает: добавляет форму контроля в конец списка ветвей предмета.
    // Выход: структура обновлена.
    void addEvent(string subject, string event);

    // Вход: нет.
    // Что делает: выводит структуру на экран (ствол вертикально, ветви горизонтально).
    // Выход: нет.
    void display();

    // Вход: название предмета, название формы контроля.
    // Что делает: удаляет форму контроля из списка ветвей предмета.
    // Выход: структура обновлена.
    void deleteEvent(string subject, string event);

    // Вход: название учебного предмета.
    // Что делает: удаляет предмет и освобождает память всех связанных с ним форм контроля.
    // Выход: структура обновлена.
    void deleteSubject(string subject);

    // Вход: название предмета.
    // Что делает: проверяет наличие предмета в структуре без учета регистра.
    // Выход: true если предмет найден, иначе false.
    bool hasSubject(string subject);

    // Вход: название предмета, название формы контроля.
    // Что делает: проверяет наличие формы контроля у указанного предмета.
    // Выход: true если форма контроля найдена, иначе false.
    bool hasEvent(string subject, string event);

    // Вход: название предмета.
    // Что делает: выполняет регистронезависимый поиск узла предмета.
    // Выход: указатель на узел предмета или nullptr.
    SubjectNode* findSubject(string subject);

    // Вход: нет.
    // Что делает: возвращает указатель на первый элемент списка предметов.
    // Выход: указатель на голову списка предметов.
    SubjectNode* getSubjectHead() const;

    // Вход: направление сортировки (true - по возрастанию, false - по убыванию).
    // Что делает: сортирует элементы ствола (предметы) методом выбора лексикографически.
    // Выход: структура упорядочена.
    void sortSubjects(bool ascending);

    // Вход: название формы контроля.
    // Что делает: ищет в структуре все предметы, имеющие указанную форму контроля, и выводит их.
    // Выход: количество найденных предметов.
    int findSubjectsByEvent(string event);

    // Вход: имя текстового файла.
    // Что делает: сохраняет всю структуру в текстовый файл.
    // Выход: нет.
    void saveToFile(string filename);

    // Вход: имя текстового файла.
    // Что делает: читает данные из файла и восстанавливает структуру в памяти.
    // Выход: структура заполнена.
    void loadFromFile(string filename);

    // Вход: нет.
    // Что делает: поузлово освобождает память всех предметов и форм контроля.
    // Выход: память очищена.
    void clear();
};