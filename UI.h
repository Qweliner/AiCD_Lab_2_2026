//UI.h
#pragma once
#include <string>
#include "Structure.h"

// Вход: исходная строка.
// Что делает: удаляет пробелы и символы перевода строки в начале и в конце.
// Выход: очищенная строка.
std::string trim(const std::string& str);

// Вход: строка приглашения к вводу.
// Что делает: выводит приглашение и считывает строку пользователя.
// Выход: введенная строка.
std::string readLine(const std::string& prompt);

// Вход: имя файла.
// Что делает: проверяет физическое наличие файла на диске.
// Выход: true если файл существует, иначе false.
bool fileExists(const std::string& filename);

// Вход: имя файла, ссылка на строку для текста ошибки.
// Что делает: проверяет допустимость имени файла для ОС Windows.
// Выход: true если имя корректно, иначе false.
bool isValidFileName(const std::string& filename, std::string& errorMsg);

// Вход: название предмета, ссылка на строку для текста ошибки.
// Что делает: выполняет логическую проверку имени предмета (длина, отсутствие пробелов, цифр и спецсимволов).
// Выход: true если название валидно, иначе false.
bool isValidSubjectName(const string& str, string& errorMsg);

// Вход: название формы контроля, ссылка на строку для текста ошибки.
// Что делает: выполняет логическую проверку формы контроля (длина, отсутствие пробелов, цифр и спецсимволов).
// Выход: true если название валидно, иначе false.
bool isValidEventName(const string& str, string& errorMsg);

// Вход: нет.
// Что делает: выводит шапку программы в консоль.
// Выход: нет.
void Greeting();

// Вход: нет.
// Что делает: выводит список доступных пунктов меню.
// Выход: нет.
void printMenu();

// Вход: нет.
// Что делает: ожидает нажатия любой клавиши клавиатуры.
// Выход: нет.
void pressAnyKey();

// Вход: ссылка на структуру StudyStructure.
// Что делает: запускает диалог циклического добавления учебных предметов до ввода 0.
// Выход: структура обновлена.
void handleAddSubject(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: запускает диалог циклического добавления форм контроля к предмету до ввода 0.
// Выход: структура обновлена.
void handleAddEvent(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: выводит на экран текущее состояние структуры ведомости.
// Выход: нет.
void handleDisplayStructure(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: циклически запрашивает и удаляет выбранные формы контроля до ввода 0.
// Выход: структура обновлена.
void handleDeleteEvent(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: циклически удаляет предметы с подтверждением при наличии ветвей до ввода 0.
// Выход: структура обновлена.
void handleDeleteSubject(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: валидирует имя файла, проверяет перезапись и сохраняет данные.
// Выход: нет.
void handleSaveToFile(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: запрашивает направление и запускает лексикографическую сортировку предметов.
// Выход: нет.
void handleSortSubjects(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: запрашивает форму контроля, приводит к верхнему регистру и выполняет поиск предметов.
// Выход: нет.
void handleSearchByEvent(StudyStructure& structure);

// Вход: ссылка на структуру StudyStructure.
// Что делает: циклически запрашивает имя файла, режим импорта и заполняет структуру.
// Выход: структура обновлена.
void handleLoadFromFile(StudyStructure& structure);